"""Числа словами українською — щоб синтез не читав цифри як телеграму."""
ONES = ["", "один", "два", "три", "чотири", "п'ять", "шість", "сім", "вісім", "дев'ять",
        "десять", "одинадцять", "дванадцять", "тринадцять", "чотирнадцять", "п'ятнадцять",
        "шістнадцять", "сімнадцять", "вісімнадцять", "дев'ятнадцять"]
ONES_F = {1: "одна", 2: "дві"}
TENS = ["", "", "двадцять", "тридцять", "сорок", "п'ятдесят", "шістдесят", "сімдесят",
        "вісімдесят", "дев'яносто"]
HUNDREDS = ["", "сто", "двісті", "триста", "чотириста", "п'ятсот", "шістсот", "сімсот",
            "вісімсот", "дев'ятсот"]
HOURS = ["нульова", "перша", "друга", "третя", "четверта", "п'ята", "шоста", "сьома",
         "восьма", "дев'ята", "десята", "одинадцята", "дванадцята", "тринадцята",
         "чотирнадцята", "п'ятнадцята", "шістнадцята", "сімнадцята", "вісімнадцята",
         "дев'ятнадцята", "двадцята", "двадцять перша", "двадцять друга", "двадцять третя"]

def num(n, fem=False):
    n = int(n)
    if n < 0:
        return "мінус " + num(-n, fem)
    if n < 20:
        return (ONES_F.get(n) if fem else None) or ONES[n] or "нуль"
    if n < 100:
        rest = num(n % 10, fem) if n % 10 else ""
        return (TENS[n // 10] + (" " + rest if rest else "")).strip()
    if n < 1000:
        rest = num(n % 100, fem) if n % 100 else ""
        return (HUNDREDS[n // 100] + (" " + rest if rest else "")).strip()
    return str(n)

def plural(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many

def hhmm(s):
    """'22:00' -> 'двадцять друга година', '18:30' -> 'вісімнадцята тридцять'"""
    h, m = (int(x) for x in s.split(":"))
    if m == 0:
        return f"{HOURS[h % 24]} година"
    return f"{HOURS[h % 24]} {num(m)}"

def minutes(total):
    h, m = divmod(int(total), 60)
    out = []
    if h:
        out.append(f"{num(h, fem=True)} {plural(h, 'година', 'години', 'годин')}")
    if m:
        out.append(f"{num(m, fem=True)} {plural(m, 'хвилина', 'хвилини', 'хвилин')}")
    return " ".join(out) or "менше хвилини"

def degrees(t):
    return f"{num(t)} {plural(t, 'градус', 'градуси', 'градусів')}"

def percent(p):
    return f"{num(p)} {plural(p, 'відсоток', 'відсотки', 'відсотків')}"

HOURS_LOC = ["нульовій", "першій", "другій", "третій", "четвертій", "п'ятій", "шостій",
             "сьомій", "восьмій", "дев'ятій", "десятій", "одинадцятій", "дванадцятій",
             "тринадцятій", "чотирнадцятій", "п'ятнадцятій", "шістнадцятій", "сімнадцятій",
             "вісімнадцятій", "дев'ятнадцятій", "двадцятій", "двадцять першій",
             "двадцять другій", "двадцять третій"]
HOURS_GEN = [h[:-1] + "ої" if h.endswith("а") else h for h in
             ["нульова", "перша", "друга", "третя", "четверта", "п'ята", "шоста", "сьома",
              "восьма", "дев'ята", "десята", "одинадцята", "дванадцята", "тринадцята",
              "чотирнадцята", "п'ятнадцята", "шістнадцята", "сімнадцята", "вісімнадцята",
              "дев'ятнадцята", "двадцята", "двадцять перша", "двадцять друга", "двадцять третя"]]
GEN = ["нуля", "одного", "двох", "трьох", "чотирьох", "п'яти", "шести", "семи", "восьми",
       "дев'яти", "десяти", "одинадцяти", "дванадцяти", "тринадцяти", "чотирнадцяти",
       "п'ятнадцяти", "шістнадцяти", "сімнадцяти", "вісімнадцяти", "дев'ятнадцяти",
       "двадцяти"]

def gen(n):
    n = int(n)
    return GEN[n] if 0 <= n <= 20 else num(n)

def at_time(s):
    """'22:00' -> 'о двадцять другій', '18:30' -> 'о вісімнадцятій тридцять'"""
    h, m = (int(x) for x in s.split(":"))
    return f"о {HOURS_LOC[h % 24]}" + (f" {num(m)}" if m else "")

def from_to(a, b):
    ha, ma = (int(x) for x in a.split(":"))
    hb, mb = (int(x) for x in b.split(":"))
    return (f"з {HOURS_GEN[ha % 24]}" + (f" {num(ma)}" if ma else "") +
            f" до {HOURS_GEN[hb % 24]}" + (f" {num(mb)}" if mb else ""))

def cherga(c):
    """'4.1' -> 'чотири-один'"""
    return "-".join(num(int(x)) for x in str(c).split("."))
